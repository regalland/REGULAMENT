if(typeof IntersectionObserver !== 'undefined'){
  const observer = new IntersectionObserver(entries => {
    entries.forEach(en => { if(en.isIntersecting) setActivePart(en.target.id); });
  }, { rootMargin:'-12% 0px -70% 0px', threshold:0 });
  allParts.forEach(p => observer.observe(p));

  const chapterObserver = new IntersectionObserver(entries => {
    entries.forEach(en => {
      if(!en.isIntersecting) return;
      setActiveChapter(en.target.id);
      const part = en.target.closest('.part-sec');
      if(part) setActivePart(part.id);
    });
  }, { rootMargin:'-12% 0px -70% 0px', threshold:0 });
  allChapters.forEach(ch => chapterObserver.observe(ch));
}
