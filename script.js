function manualHlRe(){ return /\{\{(?:(ban|warn|forbid|allow|exception|time|money|term|none)\|)?([^{}]+)\}\}/g; }
function stripManualHl(text){
  return String(text==null?'':text).replace(manualHlRe(), function(m, cls, content){ return content; });
}

function decorate(text, tokens){
  const manuals = [];
  const raw = String(text==null?'':text).replace(manualHlRe(), function(m, cls, content){
    const idx = manuals.length;
    manuals.push({ cls: cls || 'custom', content: content });
    return '\u0001MH' + idx + '\u0001';
  });
  const safe = escapeHtml(raw);
  let result;
  if(!tokens || !tokens.length){
    result = safe.replace(KW_RE, function(match, ...rest){
      const caps = rest.slice(0, KW_CLASSES.length);
      const idx = caps.findIndex(g => g !== undefined);
      return idx === -1 ? match : '<span class="kw ' + KW_CLASSES[idx] + '">' + match + '</span>';
    });
  } else {
    const searchPatterns = tokens.map(t => '(' + escapeRegex(escapeHtml(t)) + ')');
    const all = searchPatterns.concat(KW_PATTERNS);
    const re = new RegExp(all.join('|'), 'gi');
    result = safe.replace(re, function(match, ...rest){
      const caps = rest.slice(0, all.length);
      const idx = caps.findIndex(g => g !== undefined);
      if(idx === -1) return match;
      if(idx < searchPatterns.length) return '<mark>' + match + '</mark>';
      return '<span class="kw ' + KW_CLASSES[idx - searchPatterns.length] + '">' + match + '</span>';
    });
  }
  if(manuals.length){
    result = result.replace(/\u0001MH(\d+)\u0001/g, function(m, i){
      const mh = manuals[+i];
      if(mh.cls === 'none') return escapeHtml(mh.content);
      return '<span class="kw kw-' + mh.cls + '">' + escapeHtml(mh.content) + '</span>';
    });
  }
  return result;
}

